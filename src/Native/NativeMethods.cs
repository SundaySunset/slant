    public static string GetWindowClassNameSafe(IntPtr hwnd)
    {
        if (hwnd == IntPtr.Zero) return string.Empty;
        StringBuilder sb = new(128);
        int len = GetClassName(hwnd, sb, sb.Capacity);
        return len > 0 ? sb.ToString() : string.Empty;
    }

    public static void EnableDarkTitleBar(IntPtr hwnd)
    {
        if (hwnd == IntPtr.Zero) return;
        int dark = 1;
        if (DwmSetWindowAttribute(hwnd, DWMWA_USE_IMMERSIVE_DARK_MODE, ref dark, sizeof(int)) != 0)
        {
            DwmSetWindowAttribute(hwnd, DWMWA_USE_IMMERSIVE_DARK_MODE_BEFORE_20H1, ref dark, sizeof(int));
        }
    }

    public static void ApplyWin11MenuStyle(IntPtr hwnd, bool isDark, int borderColorRef)
    {
        if (hwnd == IntPtr.Zero) return;
        try
        {
            int dark = isDark ? 1 : 0;
            if (DwmSetWindowAttribute(hwnd, DWMWA_USE_IMMERSIVE_DARK_MODE, ref dark, sizeof(int)) != 0)
            {
                DwmSetWindowAttribute(hwnd, DWMWA_USE_IMMERSIVE_DARK_MODE_BEFORE_20H1, ref dark, sizeof(int));
            }

            int cornerPref = DWMWCP_ROUND;
            DwmSetWindowAttribute(hwnd, DWMWA_WINDOW_CORNER_PREFERENCE, ref cornerPref, sizeof(int));

            int border = borderColorRef;
            DwmSetWindowAttribute(hwnd, DWMWA_BORDER_COLOR, ref border, sizeof(int));
        }
        catch
        {
            // Older Windows builds ignore unsupported DWM attributes.
        }
    }

    public static (int Width, int Height) GetPrimaryMonitorPhysicalResolution()
    {
        Screen? primary = Screen.PrimaryScreen;
        try
        {
            DEVMODE devMode = new()
            {
                dmDeviceName = string.Empty,
                dmFormName = string.Empty,
                dmSize = (ushort)Marshal.SizeOf<DEVMODE>()
            };

            string? deviceName = primary?.DeviceName;
            if (EnumDisplaySettings(deviceName, ENUM_CURRENT_SETTINGS, ref devMode) &&
                devMode.dmPelsWidth > 0 &&
                devMode.dmPelsHeight > 0)
            {
                return ((int)devMode.dmPelsWidth, (int)devMode.dmPelsHeight);
            }
        }
        catch
        {
            // Fall through to Screen.PrimaryScreen bounds.
        }

        if (primary is not null && primary.Bounds.Width > 0 && primary.Bounds.Height > 0)
        {
            return (primary.Bounds.Width, primary.Bounds.Height);
        }

        return (1920, 1080);
    }
